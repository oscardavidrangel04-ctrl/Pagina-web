const fs = require('fs');
const path = require('path');
const {chromium} = require('C:/Users/Casa/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
(async()=>{
 const root=path.resolve(__dirname,'..');
 const browser=await chromium.launch({headless:true,channel:'msedge'});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.route('**/*',async route=>{
  const url=new URL(route.request().url());
  if(url.hostname!=='local.test')return route.abort();
  const target=path.resolve(root,'.'+decodeURIComponent(url.pathname));
  if(!target.startsWith(root+path.sep)||!fs.existsSync(target))return route.fulfill({status:404,body:''});
  const type=target.endsWith('.css')?'text/css':target.endsWith('.js')?'application/javascript':target.endsWith('.svg')?'image/svg+xml':target.endsWith('.html')?'text/html':'application/octet-stream';
  await route.fulfill({contentType:type,body:fs.readFileSync(target)});
 });
 await page.goto('http://local.test/calculadoras/salario-neto.html');
 if(await page.locator('h1').count()!==1)throw Error('H1');
 if(!await page.title().then(t=>t.includes('sueldo neto 2026')))throw Error('SEO title');
 const description=await page.locator('meta[name="description"]').getAttribute('content');
 if(!description||!description.includes('salario bruto'))throw Error('Meta description');
 const schemas=await page.evaluate(()=>Array.from(document.querySelectorAll('script[type="application/ld+json"]')).map(e=>JSON.parse(e.textContent)));
 if(!JSON.stringify(schemas).includes('WebApplication'))throw Error('WebApplication schema');
 await page.locator('#salario').fill('20000');
 await page.locator('#isrManual').fill('2500');
 await page.locator('#imss').fill('500');
 await page.locator('#otras').fill('0');
 await page.locator('.calc-button').click();
 if(!(await page.locator('#resultado').innerText()).includes('17,000'))throw Error('Wrong net result');
 await page.evaluate(()=>window.scrollTo(0,0));
 await page.screenshot({path:path.join(root,'outputs/salario-neto-desktop.png'),fullPage:false});
 await page.setViewportSize({width:390,height:844});
 await page.evaluate(()=>window.scrollTo(0,0));
 if(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth))throw Error('Mobile overflow');
 const brokenAnchors=await page.evaluate(()=>Array.from(document.querySelectorAll('a[href^="#"]')).map(a=>a.getAttribute('href').slice(1)).filter(id=>id&&!document.getElementById(id)));
 if(brokenAnchors.length)throw Error('Broken anchors: '+brokenAnchors.join(','));
 await page.screenshot({path:path.join(root,'outputs/salario-neto-mobile.png'),fullPage:false});
 await page.locator('.faq-section').scrollIntoViewIfNeeded();
 await page.locator('.faq-section details').first().click();
 await page.screenshot({path:path.join(root,'outputs/salario-neto-faq-mobile.png'),fullPage:false});
 await page.evaluate(()=>document.documentElement.dataset.theme='dark');
 if(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth))throw Error('Dark overflow');
 if(errors.length)throw Error(errors.join('\n'));
 console.log('Desktop/mobile, calculation, SEO schema, FAQ and browser errors: OK');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
