const fs = require('fs');
const path = require('path');
const {chromium} = require('C:/Users/Casa/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
(async()=>{
 const root=path.resolve(__dirname,'..');
 const browser=await chromium.launch({headless:true,channel:'msedge'});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.route('**/*',async route=>{
  const url=new URL(route.request().url());
  if(url.hostname!=='local.test')return route.abort();
  const target=path.resolve(root,'.'+decodeURIComponent(url.pathname));
  if(!target.startsWith(root+path.sep)||!fs.existsSync(target))return route.fulfill({status:404,body:''});
  const type=target.endsWith('.css')?'text/css':target.endsWith('.js')?'application/javascript':target.endsWith('.svg')?'image/svg+xml':target.endsWith('.html')?'text/html':'application/octet-stream';
  await route.fulfill({contentType:type,body:fs.readFileSync(target)});
 });
 await page.goto('http://local.test/articulos/cuando-pagan-finiquito.html');
 await page.locator('.fp-cover').waitFor();
 if(await page.locator('h1').count()!==1)throw Error('H1');
 await page.evaluate(()=>window.scrollTo(0,0));
 await page.screenshot({path:path.join(root,'outputs/finiquito-editorial-desktop.png'),fullPage:false});
 await page.locator('#retraso').scrollIntoViewIfNeeded();
 await page.screenshot({path:path.join(root,'outputs/finiquito-editorial-steps.png'),fullPage:false});
 const brokenAnchors=await page.evaluate(()=>Array.from(document.querySelectorAll('a[href^="#"]')).map(a=>a.getAttribute('href').slice(1)).filter(id=>id&&!document.getElementById(id)));
 if(brokenAnchors.length)throw Error('Broken anchors: '+brokenAnchors.join(','));
 await page.setViewportSize({width:390,height:844});
 await page.evaluate(()=>window.scrollTo(0,0));
 if(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth))throw Error('Mobile overflow');
 await page.screenshot({path:path.join(root,'outputs/finiquito-editorial-mobile.png'),fullPage:false});
 if(errors.length)throw Error(errors.join('\n'));
 await page.locator('.fp-faq summary').first().click();
 if(!await page.locator('.fp-faq').first().evaluate(e=>e.open))throw Error('FAQ');
 await page.locator('#preguntas').scrollIntoViewIfNeeded();
 await page.screenshot({path:path.join(root,'outputs/finiquito-editorial-faq-mobile.png'),fullPage:false});
 await page.evaluate(()=>document.querySelectorAll('script[type="application/ld+json"]').forEach(e=>JSON.parse(e.textContent)));
 await page.evaluate(()=>document.documentElement.dataset.theme='dark');
 if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Dark overflow');
 await page.screenshot({path:path.join(root,'outputs/finiquito-editorial-dark-mobile.png'),fullPage:false});
 console.log('Desktop/mobile, FAQ, schema and browser errors: OK');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
